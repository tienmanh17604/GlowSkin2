/**
 * Lấy chu trình đã gán cố định cho tài khoản/người dùng:
 * - Mỗi tài khoản được phân bổ 1 chu trình ngẫu nhiên riêng biệt.
 * - Lưu vào localStorage theo ID/Email của tài khoản đó.
 * - Khi ấn "Nhận chu trình" nhiều lần hoặc tải lại trang, chu trình của tài khoản đó luôn được giữ nguyên cố định.
 */
export function getAssignedRoutineIndex(user) {
  const userId = user
    ? (user.id || user._id || user.email || user.username || "user")
    : "guest";
  const storageKey = `glowskin_assigned_routine_${userId}`;

  try {
    const saved = localStorage.getItem(storageKey);
    if (saved !== null) {
      const parsed = parseInt(saved, 10);
      if (!isNaN(parsed) && parsed >= 0 && parsed < PERSONALIZED_ROUTINES.length) {
        return parsed;
      }
    }
  } catch (e) {}

  let assignedIndex = 0;
  if (user) {
    const str = String(userId);
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
      hash = ((hash << 5) - hash) + str.charCodeAt(i);
      hash |= 0;
    }
    assignedIndex = Math.abs((hash * 31) ^ 0x5bd1e995) % PERSONALIZED_ROUTINES.length;
  } else {
    assignedIndex = Math.floor(Math.random() * PERSONALIZED_ROUTINES.length);
  }

  try {
    localStorage.setItem(storageKey, String(assignedIndex));
  } catch (e) {}

  return assignedIndex;
}
